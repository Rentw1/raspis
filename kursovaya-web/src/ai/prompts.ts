// ---------------- Главы ----------------

export interface ChapterPartArgs {
  cw: Coursework;
  section: Section;
  chapter: PlanChapter;
  part: number;
  parts: number;
  words: number;
  pointsHere: string[];
  previousTail: string;
  sourcesList: string;
  minCitations: number;
  tables: [number, string][];
  appendixRefs: [number, string][];
  last: boolean;
  facts?: string;
  reference?: string;
  continuation?: boolean;
}

export function chapterPartRequest(a: ChapterPartArgs): string {
  const m = a.cw.meta;
  const out: string[] = [workContext(a.cw), planOutline(a.cw)];
  const role =
    a.section.role === 'theory'
      ? 'теоретическая глава: понятия и определения разных авторов с ссылками, сущность, классификации, признаки, факторы, ' +
        'нормативное регулирование, современные подходы и проблемы'
      : 'практическая глава: анализ фактического материала по теме — показатели, динамика, структура, расчёты ' +
        '(абсолютные и относительные отклонения, темпы роста, доли), выводы по каждому показателю, выявленные проблемы и рекомендации';
  out.push(`Сейчас пишется ГЛАВА ${a.section.number} «${a.chapter.title}» — ${role}.`);
  out.push(
    `Объём всей главы — около ${a.section.targetWords} слов. Эта часть — ${a.part} из ${a.parts}: около ${a.words} слов (не меньше ${Math.round(a.words * 0.85)}).`,
  );
  out.push('Смысловые пункты главы (в тексте без подзаголовков):');
  a.chapter.points.forEach((p, i) => out.push(`${i + 1}. ${p}${a.pointsHere.includes(p) ? '  ← раскрыть в этой части' : ''}`));
  if (a.continuation) {
    out.push(
      'Глава уже написана, но короче нужного. Допиши продолжение: раскрой подробнее пункты, отмеченные стрелкой, ' +
        'добавь примеры, сравнения, расчёты; не повторяй уже написанное.',
    );
  }
  if (a.previousTail.trim()) {
    out.push('Конец уже написанного текста главы (продолжай с нового абзаца, не повторяя его):');
    out.push(`«${a.previousTail.trim()}»`);
  } else {
    out.push('Это начало главы: начни с вводного абзаца о задачах главы (без слов «в данной главе мы»).');
  }
  if (a.section.role !== 'theory') {
    if (m.practiceData.trim()) {
      out.push('ИСХОДНЫЕ ДАННЫЕ ОТ СТУДЕНТА (используй в первую очередь, цифры не искажай):');
      out.push(truncate(m.practiceData.trim(), 3500));
    }
    if ((a.facts ?? '').trim()) {
      out.push('ФАКТИЧЕСКИЙ МАТЕРИАЛ ИЗ ИНТЕРНЕТА (можно использовать с указанием, откуда данные):');
      out.push((a.facts as string).trim());
    }
    out.push(
      'Если конкретных данных организации нет — анализ строится на открытой статистике из материалов выше ' +
        'или на условном примере; в этом случае прямо укажи, что расчёт выполнен на условных данных.',
    );
  } else if ((a.reference ?? '').trim()) {
    out.push('Справочные сведения для точности (не цитировать и не ссылаться на них):');
    out.push(truncate((a.reference as string).trim(), 2500));
  }
  if (a.tables.length) {
    for (const [n, title] of a.tables) {
      out.push(
        `В этой части обязательно приведи таблицу ${n} «${title}». Перед таблицей в тексте дай на неё ссылку ` +
          `(«…представлены в таблице ${n}»), после таблицы — абзац с анализом её данных.`,
      );
    }
    out.push(
      'Формат таблицы (строго):\n' +
        'Таблица N — Название таблицы\n' +
        '| Заголовок 1 | Заголовок 2 | Заголовок 3 |\n' +
        '| значение | значение | значение |\n' +
        'Не более 12 строк и 6 столбцов, в ячейках кратко, числа с одинаковым количеством знаков после запятой, ' +
        'единицы измерения — в заголовках столбцов; пустых ячеек нет — ставь прочерк «–».',
    );
  }
  for (const [n, title] of a.appendixRefs) {
    out.push(`В тексте этой части сошлись на приложение ${n} («${title}») в скобках: «(приложение ${n})».`);
  }
  if (a.last) out.push('Заверши главу абзацем-выводом, который начинается словами «Таким образом,» и кратко обобщает результаты главы.');
  out.push(
    `Список литературы (ссылайся по номерам; в этой части не меньше ${a.minCitations} ссылок на разные источники, ` +
      'с номерами страниц там, где указан объём или страницы):',
  );
  out.push(a.sourcesList);
  out.push('Напиши только текст этой части главы — абзацы через пустую строку.');
  return `${out.join('\n')}\n`;
}

// ---------------- Введение и заключение ----------------

export function chapterDigest(cw: Coursework, perChapter = 900): string {
  const out: string[] = [];
  for (const c of chaptersOf(cw)) {
    const paras = c.text
      .split(/\n\s*\n/)
      .map((e) => e.trim())
      .filter((e) => e && !e.startsWith('|') && !e.startsWith('Таблица'));
    if (!paras.length) continue;
    const firstP = paras[0];
    let lastP = paras[paras.length - 1];
    for (let i = paras.length - 1; i >= 0; i--) {
      if (paras[i].startsWith('Таким образом')) {
        lastP = paras[i];
        break;
      }
    }
    out.push(`Глава ${c.number}. ${c.title}:`);
    out.push(truncate(`${firstP} … ${lastP}`, perChapter));
    out.push('');
  }
  return `${out.join('\n')}\n`;
}

export function introductionRequest(cw: Coursework, a: { words: number; sourcesList: string; sourcesCount: number; appendicesCount: number }): string {
  const p = cw.plan ?? emptyPlan();
  const n = chaptersOf(cw).length;
  const struct =
    `Структура работы: курсовая работа состоит из введения, ${chaptersGenitive(n)}, заключения, ` +
    `списка литературы из ${a.sourcesCount} ${plural(a.sourcesCount, 'источника', 'источников', 'источников')}` +
    `${a.appendicesCount > 0 ? ` и ${a.appendicesCount} ${plural(a.appendicesCount, 'приложения', 'приложений', 'приложений')}` : ''}.`;
  return (
    `${workContext(cw)}\n` +
    `${planOutline(cw)}\n` +
    `Основная часть уже написана. Краткое содержание глав:\n${chapterDigest(cw)}\n` +
    `Напиши ВВЕДЕНИЕ объёмом около ${a.words} слов (2–2,5 страницы), не делая подзаголовков. Порядок абзацев:\n` +
    '1) актуальность темы (2–3 абзаца, с конкретикой и 1–2 ссылками);\n' +
    '2) краткий обзор литературы: чьи работы использованы и что в них рассмотрено (1–2 абзаца, ссылки на 5–8 разных источников);\n' +
    `3) «Объект исследования – ${p.object || '…'}.»;\n` +
    `4) «Предмет исследования – ${p.subject || '…'}.»;\n` +
    `5) «Цель работы – ${p.goal || '…'}.»;\n` +
    `6) «Для достижения цели поставлены следующие задачи:» и задачи списком с «– »${p.tasks.length ? ` (задачи: ${p.tasks.join('; ')})` : ''};\n` +
    `7) «Методы исследования: …»${p.methods.length ? ` (${p.methods.join(', ')})` : ''};\n` +
    '8) практическая значимость работы (1 абзац);\n' +
    `9) последний абзац — «${struct}»\n` +
    `Список литературы (ссылайся по номерам):\n${a.sourcesList}\n` +
    'Напиши только текст введения — абзацы через пустую строку.'
  );
}

export function conclusionRequest(cw: Coursework, words: number): string {
  const p = cw.plan ?? emptyPlan();
  return (
    `${workContext(cw)}\n` +
    `${planOutline(cw)}\n` +
    `Краткое содержание глав:\n${chapterDigest(cw, 1400)}\n` +
    `${p.tasks.length ? `Задачи работы: ${p.tasks.join('; ')}.\n` : ''}` +
    `Напиши ЗАКЛЮЧЕНИЕ объёмом около ${words} слов (примерно как введение, 2–2,5 страницы), без подзаголовков и без ссылок на источники. ` +
    'Содержание: краткая формулировка результатов по каждой задаче и главе (с ключевыми цифрами из практической части), ' +
    'основные выводы, рекомендации, практическая значимость работы, направления дальнейшего исследования. ' +
    'Не вводи новых фактов, которых нет в главах. Первый абзац начни словами «В ходе выполнения курсовой работы». ' +
    'Напиши только текст заключения — абзацы через пустую строку.'
  );
}

