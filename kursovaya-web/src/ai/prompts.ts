export function workContext(cw: Coursework): string {
  const m = cw.meta;
  const lines = [
    `Тема курсовой работы: «${m.topic.trim()}».`,
    `Дисциплина (междисциплинарный курс): ${m.discipline.trim() || 'не указана'}.`,
    `Специальность: ${m.specialty.trim() || 'не указана'}; ${m.course} курс СПО.`,
  ];
  if (m.organization.trim()) lines.push(`Организация (база практики) для практической части: ${m.organization.trim()}.`);
  if (m.wishes.trim()) lines.push(`Пожелания студента к содержанию: ${m.wishes.trim()}`);
  return `${lines.join('\n')}\n`;
}

export function planOutline(cw: Coursework): string {
  const p = cw.plan;
  if (!p) return '';
  const lines: string[] = [];
  if (p.object) lines.push(`Объект исследования: ${p.object}.`);
  if (p.subject) lines.push(`Предмет исследования: ${p.subject}.`);
  if (p.goal) lines.push(`Цель работы: ${p.goal}.`);
  lines.push('Основная часть (главы без параграфов):');
  p.chapters.forEach((c, i) => lines.push(`Глава ${i + 1}. ${c.title} — ${c.role === 'theory' ? 'теоретическая' : 'практическая'}.`));
  return `${lines.join('\n')}\n`;
}

