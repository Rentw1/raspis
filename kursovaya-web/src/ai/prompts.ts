export function sourcesForPrompt(ordered: Source[], annotation = 200, withAnnotations = true): string {
  return ordered
    .map((s, i) => {
      const extra: string[] = [];
      if (s.pages) extra.push(`страницы ${s.pages}`);
      if (s.pageCount && s.pageCount > 0) extra.push(`объём ${s.pageCount} с.`);
      let line = `[${i + 1}] ${shortLabel(s)}`;
      if (extra.length) line += ` (${extra.join(', ')})`;
      if (withAnnotations && (s.annotation ?? '').trim()) line += `. Кратко: ${truncate((s.annotation as string).trim(), annotation)}`;
      return `${line}\n`;
    })
    .join('');
}

