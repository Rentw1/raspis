  static String workContext(Coursework cw) {
    final m = cw.meta;
    final b = StringBuffer()
      ..writeln('Тема курсовой работы: «${m.topic.trim()}».')
      ..writeln('Дисциплина (междисциплинарный курс): ${m.discipline.trim().isEmpty ? 'не указана' : m.discipline.trim()}.')
      ..writeln('Специальность: ${m.specialty.trim().isEmpty ? 'не указана' : m.specialty.trim()}; ${m.course} курс СПО.');
    if (m.organization.trim().isNotEmpty) b.writeln('Организация (база практики) для практической части: ${m.organization.trim()}.');
    if (m.wishes.trim().isNotEmpty) b.writeln('Пожелания студента к содержанию: ${m.wishes.trim()}');
    return b.toString();
  }

  static String planOutline(Coursework cw) {
    final p = cw.plan;
    if (p == null) return '';
    final b = StringBuffer();
    if (p.object.isNotEmpty) b.writeln('Объект исследования: ${p.object}.');
    if (p.subject.isNotEmpty) b.writeln('Предмет исследования: ${p.subject}.');
    if (p.goal.isNotEmpty) b.writeln('Цель работы: ${p.goal}.');
    b.writeln('Основная часть (главы без параграфов):');
    for (var i = 0; i < p.chapters.length; i++) {
      final c = p.chapters[i];
      b.writeln('Глава ${i + 1}. ${c.title} — ${c.role == 'theory' ? 'теоретическая' : 'практическая'}.');
    }
    return b.toString();
  }

