  static String sourcesForPrompt(List<Source> ordered, {int annotation = 200, bool withAnnotations = true}) {
    final b = StringBuffer();
    for (var i = 0; i < ordered.length; i++) {
      final s = ordered[i];
      final desc = Gost.shortLabel(s);
      final extra = <String>[];
      if (s.pages != null && s.pages!.isNotEmpty) extra.add('страницы ${s.pages}');
      if (s.pageCount != null && s.pageCount! > 0) extra.add('объём ${s.pageCount} с.');
      b.write('[${i + 1}] $desc');
      if (extra.isNotEmpty) b.write(' (${extra.join(', ')})');
      if (withAnnotations && (s.annotation ?? '').trim().isNotEmpty) b.write('. Кратко: ${truncate(s.annotation!.trim(), annotation)}');
      b.writeln();
    }
    return b.toString();
  }

