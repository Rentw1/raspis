  static String rewriteRequest(Coursework cw, Section s, String mode, {String sourcesList = ''}) {
    final what = switch (mode) {
      'extend' => 'Расширь текст примерно на 40%: добавь конкретику, примеры, расчёты и ссылки на источники; сохрани структуру, таблицы и все ссылки.',
      'shorten' => 'Сократи текст примерно на 30%, убрав повторы и общие фразы; сохрани таблицы, ссылки и выводы.',
      _ => 'Перепиши текст своими словами (перефразируй), сохранив смысл, факты, цифры, таблицы и ссылки на источники.',
    };
    return '${workContext(cw)}\n'
        'Раздел: ${s.shortName}${s.kind == SectionKind.chapter ? ' «${s.title}»' : ''}.\n'
        '$what\n'
        'Формат прежний: абзацы через пустую строку, перечисления с «– », таблицы в виде «Таблица N — …» и строк «| … |».\n'
        '${sourcesList.isNotEmpty ? 'Список литературы:\n$sourcesList\n' : ''}'
        'ТЕКСТ:\n${s.text}';
  }

