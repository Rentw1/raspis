  static String chapterPartRequest({
    required Coursework cw,
    required Section section,
    required PlanChapter chapter,
    required int part,
    required int parts,
    required int words,
    required List<String> pointsHere,
    required String previousTail,
    required String sourcesList,
    required int minCitations,
    required List<(int, String)> tables,
    required List<(int, String)> appendixRefs,
    required bool last,
    String facts = '',
    String reference = '',
    bool continuation = false,
  }) {
    final m = cw.meta;
    final b = StringBuffer()
      ..writeln(workContext(cw))
      ..writeln(planOutline(cw));
    final role = section.role == 'theory'
        ? 'теоретическая глава: понятия и определения разных авторов с ссылками, сущность, классификации, признаки, факторы, '
            'нормативное регулирование, современные подходы и проблемы'
        : 'практическая глава: анализ фактического материала по теме — показатели, динамика, структура, расчёты '
            '(абсолютные и относительные отклонения, темпы роста, доли), выводы по каждому показателю, выявленные проблемы и рекомендации';
    b.writeln('Сейчас пишется ГЛАВА ${section.number} «${chapter.title}» — $role.');
    b.writeln('Объём всей главы — около ${section.targetWords} слов. Эта часть — $part из $parts: около $words слов (не меньше ${(words * 0.85).round()}).');
    b.writeln('Смысловые пункты главы (в тексте без подзаголовков):');
    for (var i = 0; i < chapter.points.length; i++) {
      final mark = pointsHere.contains(chapter.points[i]) ? '  ← раскрыть в этой части' : '';
      b.writeln('${i + 1}. ${chapter.points[i]}$mark');
    }
    if (continuation) {
      b.writeln('Глава уже написана, но короче нужного. Допиши продолжение: раскрой подробнее пункты, отмеченные стрелкой, '
          'добавь примеры, сравнения, расчёты; не повторяй уже написанное.');
    }
    if (previousTail.trim().isNotEmpty) {
      b.writeln('Конец уже написанного текста главы (продолжай с нового абзаца, не повторяя его):');
      b.writeln('«${previousTail.trim()}»');
    } else {
      b.writeln('Это начало главы: начни с вводного абзаца о задачах главы (без слов «в данной главе мы»).');
    }
    if (section.role != 'theory') {
      if (m.practiceData.trim().isNotEmpty) {
        b.writeln('ИСХОДНЫЕ ДАННЫЕ ОТ СТУДЕНТА (используй в первую очередь, цифры не искажай):');
        b.writeln(truncate(m.practiceData.trim(), 3500));
      }
      if (facts.trim().isNotEmpty) {
        b.writeln('ФАКТИЧЕСКИЙ МАТЕРИАЛ ИЗ ИНТЕРНЕТА (можно использовать с указанием, откуда данные):');
        b.writeln(facts.trim());
      }
      b.writeln('Если конкретных данных организации нет — анализ строится на открытой статистике из материалов выше '
          'или на условном примере; в этом случае прямо укажи, что расчёт выполнен на условных данных.');
    } else if (reference.trim().isNotEmpty) {
      b.writeln('Справочные сведения для точности (не цитировать и не ссылаться на них):');
      b.writeln(truncate(reference.trim(), 2500));
    }
    if (tables.isNotEmpty) {
      for (final t in tables) {
        b.writeln('В этой части обязательно приведи таблицу ${t.$1} «${t.$2}». Перед таблицей в тексте дай на неё ссылку '
            '(«…представлены в таблице ${t.$1}»), после таблицы — абзац с анализом её данных.');
      }
      b.writeln('Формат таблицы (строго):\n'
          'Таблица N — Название таблицы\n'
          '| Заголовок 1 | Заголовок 2 | Заголовок 3 |\n'
          '| значение | значение | значение |\n'
          'Не более 12 строк и 6 столбцов, в ячейках кратко, числа с одинаковым количеством знаков после запятой, '
          'единицы измерения — в заголовках столбцов; пустых ячеек нет — ставь прочерк «–».');
    }
    for (final a in appendixRefs) {
      b.writeln('В тексте этой части сошлись на приложение ${a.$1} («${a.$2}») в скобках: «(приложение ${a.$1})».');
    }
    if (last) b.writeln('Заверши главу абзацем-выводом, который начинается словами «Таким образом,» и кратко обобщает результаты главы.');
    b.writeln('Список литературы (ссылайся по номерам; в этой части не меньше $minCitations ссылок на разные источники, '
        'с номерами страниц там, где указан объём или страницы):');
    b.writeln(sourcesList);
    b.writeln('Напиши только текст этой части главы — абзацы через пустую строку.');
    return b.toString();
  }

  // ---------------- Введение и заключение ----------------

  static String chapterDigest(Coursework cw, {int perChapter = 900}) {
    final b = StringBuffer();
    for (final c in cw.chapters) {
      final paras = c.text.split(RegExp(r'\n\s*\n')).map((e) => e.trim()).where((e) => e.isNotEmpty && !e.startsWith('|') && !e.startsWith('Таблица')).toList();
      if (paras.isEmpty) continue;
      final firstP = paras.first;
      final lastP = paras.lastWhere((p) => p.startsWith('Таким образом'), orElse: () => paras.last);
      b.writeln('Глава ${c.number}. ${c.title}:');
      b.writeln(truncate('$firstP … $lastP', perChapter));
      b.writeln();
    }
    return b.toString();
  }

  static String introductionRequest(Coursework cw, {required int words, required String sourcesList, required int sourcesCount, required int appendicesCount}) {
    final p = cw.plan ?? Plan();
    final n = cw.chapters.length;
    final struct = 'Структура работы: курсовая работа состоит из введения, ${chaptersGenitive(n)}, заключения, '
        'списка литературы из $sourcesCount ${plural(sourcesCount, 'источника', 'источников', 'источников')}'
        '${appendicesCount > 0 ? ' и $appendicesCount ${plural(appendicesCount, 'приложения', 'приложений', 'приложений')}' : ''}.';
    return '${workContext(cw)}\n'
        '${planOutline(cw)}\n'
        'Основная часть уже написана. Краткое содержание глав:\n${chapterDigest(cw)}\n'
        'Напиши ВВЕДЕНИЕ объёмом около $words слов (2–2,5 страницы), не делая подзаголовков. Порядок абзацев:\n'
        '1) актуальность темы (2–3 абзаца, с конкретикой и 1–2 ссылками);\n'
        '2) краткий обзор литературы: чьи работы использованы и что в них рассмотрено (1–2 абзаца, ссылки на 5–8 разных источников);\n'
        '3) «Объект исследования – ${p.object.isEmpty ? '…' : p.object}.»;\n'
        '4) «Предмет исследования – ${p.subject.isEmpty ? '…' : p.subject}.»;\n'
        '5) «Цель работы – ${p.goal.isEmpty ? '…' : p.goal}.»;\n'
        '6) «Для достижения цели поставлены следующие задачи:» и задачи списком с «– »'
        '${p.tasks.isNotEmpty ? ' (задачи: ${p.tasks.join('; ')})' : ''};\n'
        '7) «Методы исследования: …»${p.methods.isNotEmpty ? ' (${p.methods.join(', ')})' : ''};\n'
        '8) практическая значимость работы (1 абзац);\n'
        '9) последний абзац — «$struct»\n'
        'Список литературы (ссылайся по номерам):\n$sourcesList\n'
        'Напиши только текст введения — абзацы через пустую строку.';
  }

